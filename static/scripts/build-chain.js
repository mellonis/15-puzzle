// Pre-build step. Outputs:
// - public/levels/<random>.webp     (puzzle images)
// - public/levels/<random>.json     (pre-solve blob: {level, imageUrl, nextUrl, rewardUrl, sig})
// - public/levels/<random>.json     (reward blob:    {level, title, director, title_ru, sig})
// - src/services/chain-entry.js     (entry URL only)
//
// Each blob is Ed25519-signed with the same private key the genuine server
// uses, so the bundle (which embeds the matching public key) verifies fetched
// blobs locally.

import {readFileSync, writeFileSync, mkdirSync, copyFileSync, rmSync, existsSync} from 'fs';
import {join} from 'path';
import {randomBytes, createPrivateKey, sign as nodeSign} from 'node:crypto';

// DEV-ONLY fallback. CI must set PRIVATE_KEY before invoking this.
const DEV_PRIVATE_KEY = `-----BEGIN PRIVATE KEY-----
MC4CAQAwBQYDK2VwBCIEIAQRRGHXgG45dNha6gnbG3b+S0ZTZuxp/tCAU0TOj+Ys
-----END PRIVATE KEY-----
`;

if (!process.env.PRIVATE_KEY && process.env.CI) {
  throw new Error('[build-chain] PRIVATE_KEY must be set in CI; refusing to sign chain blobs with the public dev key');
}

const privateKey = createPrivateKey(process.env.PRIVATE_KEY ?? DEV_PRIVATE_KEY);
const sign = (msg) => nodeSign(null, Buffer.from(msg, 'utf8'), privateKey).toString('hex');

// BASE_URL is the path prefix the SPA is served under (e.g. "/15-puzzle"
// for GH Pages, "" for the mellonis.ru subdomain). We bake it into the
// signed URLs so the browser's relative-URL resolution lands on the
// correct host path.
const BASE = (process.env.BASE_URL ?? '').replace(/\/$/, '');
const url = (relativePath) => BASE + relativePath;

const randomHash = () => randomBytes(8).toString('hex');

const preSolveMsg = (b) => `presolve:${b.level}:${b.imageUrl}:${b.nextUrl ?? ''}:${b.rewardUrl}`;
const rewardMsg = (b) => `reward:${b.level}:${b.title}:${b.director ?? ''}:${b.title_ru ?? ''}`;

const levels = JSON.parse(readFileSync('src/levels.json', 'utf8'));
const srcImagesDir = 'src/assets/puzzles';
const outDir = 'public/levels';

if (existsSync(outDir)) rmSync(outDir, {recursive: true, force: true});
mkdirSync(outDir, {recursive: true});

const preSolveUrls = levels.map(() => url(`/levels/${randomHash()}.json`));
const rewardUrls = levels.map(() => url(`/levels/${randomHash()}.json`));

const writeBlob = (url, blob) => {
  // Strip any path prefix (e.g. /15-puzzle) and the .json suffix to get the bare hash.
  const fileName = url.split('/').pop().replace('.json', '');
  writeFileSync(join(outDir, fileName + '.json'), JSON.stringify(blob));
};

for (let i = 0; i < levels.length; i++) {
  const level = i + 1;
  const meta = levels[i];

  const webpName = randomHash();
  copyFileSync(
    join(srcImagesDir, String(level).padStart(3, '0') + '.webp'),
    join(outDir, webpName + '.webp'),
  );

  const preSolve = {
    level,
    imageUrl: url(`/levels/${webpName}.webp`),
    nextUrl: i + 1 < levels.length ? preSolveUrls[i + 1] : null,
    rewardUrl: rewardUrls[i],
  };
  preSolve.sig = sign(preSolveMsg(preSolve));
  writeBlob(preSolveUrls[i], preSolve);

  const reward = {
    level,
    title: meta.title,
    director: meta.director,
    title_ru: meta.title_ru,
  };
  reward.sig = sign(rewardMsg(reward));
  writeBlob(rewardUrls[i], reward);
}

writeFileSync(
  'src/services/chain-entry.js',
  `// Generated by scripts/build-chain.js. Do not edit.\nexport const ENTRY_URL = '${preSolveUrls[0]}';\n`,
);

console.log(`build-chain: ${levels.length} levels (${levels.length * 2} blobs), entry ${preSolveUrls[0]}`);
